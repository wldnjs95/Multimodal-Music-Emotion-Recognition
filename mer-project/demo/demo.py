def recommend(audio_path, lyrics_text, lyrics_file, mode, youtube_url):
    # audio_path: string path
    if mode == "manual":
        lyrics = lyrics_text
    elif mode == "upload" and lyrics_file is not None:
        with open(lyrics_file.name, "r", encoding="utf-8") as f:
            lyrics = f.read()
    elif mode == "youtube" and youtube_url.strip():
        audio_path, lyrics = download_youtube(youtube_url.strip(),
                                              languages=("en",),
                                              use_whisper=False)
    else:
        return [None]*5 + ["❗ Input the text or youtube link or upload the file"]

    audio_inputs, text_inputs = preprocess_audio_text(audio_path, lyrics, mode)
    print("audio_inputs:", audio_inputs)
    print("text_inputs:", text_inputs)

    with torch.no_grad():
        for k in audio_inputs:
            audio_inputs[k] = audio_inputs[k].unsqueeze(0)
        for k in text_inputs:
            text_inputs[k] = text_inputs[k].unsqueeze(0)
        output = model(audio_inputs, text_inputs)  # [1, 2]
        valence, arousal = output.squeeze().tolist()
    print(valence)
    print(arousal)
    query_va = np.array([[valence, arousal]])  # (1, 2)

    # Since cosine similarity alone gives a score of 1 for pairs like (0.51, 0.49) and (0.33, 0.33), they were mistakenly included in the recommendations, so we changed the logic.
    # Consider cosine + distance

    # sims = cosine_similarity(query_va, va_vectors)[0]
    # top_idx = np.argsort(sims)[::-1]
    alpha = 0.7   # cosine weight(0~1)

    # (query_va : shape (1,2),  va_vectors : shape (N,2))
    cos  = cosine_similarity(query_va, va_vectors)[0]     # (N,)
    dist = np.linalg.norm(va_vectors - query_va, axis=1)  # (N,)

    score = alpha * (1 - cos) + (1 - alpha) * dist        # Small is similar
    top_idx = np.argsort(score)

    recs = []
    paths = []

    for idx in top_idx:
        song_path = song_audio_paths[idx]
        if os.path.abspath(song_path) == os.path.abspath(audio_path):
            continue
        if len(recs) == 5:
            break
        paths.append(song_path)
        quadrant = va_df.iloc[idx]["Quadrant"]

        recs.append(f"{song_ids[idx]}  |  score={score[idx]:.2f}  |  V={va_vectors[idx][0]:.2f}, A={va_vectors[idx][1]:.2f}, Q={quadrant}")

    while len(paths) < 5:
        paths.append(None)
    print(paths)
    print(recs)
    return paths[0], paths[1], paths[2], paths[3], paths[4], "\n".join(recs)

