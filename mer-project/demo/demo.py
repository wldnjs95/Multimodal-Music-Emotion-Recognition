# ------------------------------------------------------------------
# Define model
# ------------------------------------------------------------------
class ASTBERTCrossAttentionRegressor(nn.Module):
    def __init__(self):
        super().__init__()
        self.ast = ASTModel.from_pretrained("MIT/ast-finetuned-audioset-10-10-0.4593")
        self.bert = BertModel.from_pretrained("bert-base-uncased")
        self.cross_attn = nn.MultiheadAttention(embed_dim=768, num_heads=8, batch_first=True)
        self.regressor = nn.Linear(768, 2)

    def forward(self, audio_inputs, text_inputs):
        audio_inputs = {k: v.to(self.ast.device) for k, v in audio_inputs.items()}
        text_inputs = {k: v.to(self.bert.device) for k, v in text_inputs.items()}
        a_seq = self.ast(**audio_inputs).last_hidden_state  # [B, T_a, 768]
        t_seq = self.bert(**text_inputs).last_hidden_state  # [B, T_t, 768]
        cross_out, _ = self.cross_attn(query=t_seq, key=a_seq, value=a_seq)
        fused = cross_out[:, 0, :]  # [B, 768] → [CLS]
        return self.regressor(fused)
# ------------------------------------------------------------------
# Load model
# ------------------------------------------------------------------
AST_WEIGHTS = "ast_bert_cross_half_training.pt"  # Weigthed model file

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model  = ASTBERTCrossAttentionRegressor().to(device)
model.load_state_dict(torch.load(AST_WEIGHTS, map_location=device))
model.eval()

# Processor & Tokenizer
ast_proc = ASTFeatureExtractor.from_pretrained("MIT/ast-finetuned-audioset-10-10-0.4593")
