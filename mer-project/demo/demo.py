def preprocess_audio_text(audio_path, lyric_path, mode):
    # audio
    waveform, sr = torchaudio.load(audio_path)

    # Split from 10 to 30 sec
    if mode == "youtube":
        start_sample = int(10 * sr)
        end_sample = int(30 * sr)
        total_len = waveform.size(-1)
        print(total_len)
        if total_len > end_sample:
            waveform = waveform[:, start_sample:end_sample]
            print("[INFO] YouTube mode: 10s ~ 30s")
        elif total_len > start_sample:
            waveform = waveform[:, start_sample:]
            print("[INFO] YouTube mode: after 10s to end")
        else:
            print("[WARN] Audio too short (<10s), using full waveform")
    else:
        print("[INFO] Full audio used (mode:", mode, ")")

    if waveform.shape[0] > 1:
        waveform = waveform.mean(dim=0)
    elif waveform.shape[0] == 1:
        waveform = waveform.squeeze(0)
    if sr != 16000:
        waveform = torchaudio.transforms.Resample(orig_freq=sr, new_freq=16000)(waveform)
    audio_inputs = ast_proc(waveform, sampling_rate=16000, return_tensors="pt")
    audio_inputs = {k: v.squeeze(0).to(device) for k, v in audio_inputs.items()}


    text_inputs = bert_tok(lyric_path, return_tensors="pt", padding="max_length", truncation=True, max_length=128)
    text_inputs = {k: v.squeeze(0).to(device) for k, v in text_inputs.items()}

    return audio_inputs, text_inputs

