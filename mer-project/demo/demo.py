"""### Audio download logic from a YouTube link + YouTube Script API call logic"""

from pathlib import Path
import yt_dlp, tempfile, os
from youtube_transcript_api import YouTubeTranscriptApi, TranscriptsDisabled

def download_youtube(url: str, languages=("en", ), use_whisper=False):
    """
    Returns
    -------
    audio_path : str  # downloaded mp3 file
    lyrics     : str  # transcript text (empty if not available)
    """
    # 1) Download & convert to mp3
    ydl_opts = {
        "format": "bestaudio/best",
        "outtmpl": os.path.join(tempfile.gettempdir(), "%(id)s.%(ext)s"),
        "postprocessors": [{"key": "FFmpegExtractAudio",
                            "preferredcodec": "mp3",
                            "preferredquality": "192"}],
        "quiet": True,
    }
    with yt_dlp.YoutubeDL(ydl_opts) as ydl:
        info        = ydl.extract_info(url, download=True)
        base        = Path(ydl.prepare_filename(info)).with_suffix(".mp3")
        audio_path  = str(base)
        video_id    = info["id"]

    # 2) Get transcript
    lyrics = ""
    try:
        transcript = YouTubeTranscriptApi.get_transcript(video_id,
                                                         languages=list(languages))
        lyrics = "\n".join(t["text"] for t in transcript)
    except TranscriptsDisabled:
        print("[WARN] transcripts disabled")
    except Exception as e:
        print(f"[WARN] transcript error: {e}")

    # # 3) Optional Whisper fallback
    # if not lyrics and use_whisper:
    #     lyrics = whisper_transcribe(audio_path, lang=languages[0])

    return audio_path, lyrics

